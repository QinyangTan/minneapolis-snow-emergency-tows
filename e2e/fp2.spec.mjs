import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('FP2 linked selections, indicators, missing data and responsive layout',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('fp2/');
 await expect(page.locator('.city-map [role="button"]')).toHaveCount(87);
 await expect(page.locator('.scatter circle')).toHaveCount(86);
 await expect(page.locator('.scope-line')).toContainText('5,355');
 await expect(page.locator('.scope-line')).toContainText('68 without');
 await page.locator('.city-map').getByRole('button',{name:/^Como:/}).click();
 await expect(page.getByTestId('selected-name')).toHaveText('Como');
 await expect(page.locator('.scatter').getByRole('button',{name:/^Como:/})).toHaveAttribute('aria-pressed','true');
 await page.getByLabel('Snow emergency',{exact:true}).selectOption('Bridge');
 await page.getByLabel('Emergency phase',{exact:true}).selectOption('2');
 await expect(page.getByTestId('selected-name')).toHaveText('Como');
 await page.getByLabel('Towing measure',{exact:true}).selectOption('rate');
 await page.getByLabel('Choose neighborhood',{exact:true}).selectOption('Humboldt Industrial Area');
 await expect(page.locator('.numbers>strong')).toHaveText('—');
 await expect(page.locator('.numbers')).toContainText('Unavailable');
 await page.getByLabel('Neighborhood indicator',{exact:true}).selectOption('salePrice');
 await expect(page.locator('.scatter circle')).toHaveCount(54);
 await page.getByLabel('Lower bound',{exact:true}).fill('25');
 await expect(page.getByLabel('Lower bound',{exact:true})).toHaveValue('25');
 await page.getByRole('button',{name:'Clear range',exact:true}).click();
 await expect(page.getByLabel('Lower bound',{exact:true})).toHaveValue('0');
 await page.getByRole('button',{name:/Reset exploration/}).click();
 await expect(page.getByTestId('selected-name')).toHaveText('Marcy Holmes');
 await page.locator('.city-map').getByRole('button',{name:/^Como:/}).focus();await page.keyboard.press('Enter');
 await expect(page.getByTestId('selected-name')).toHaveText('Como');
 await page.getByRole('button',{name:/Reset exploration/}).click();
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'artifacts/fp2-desktop.png',fullPage:true});
 await page.locator('.linked-grid').screenshot({path:'artifacts/fp2-linked-views.png'});
 await page.getByLabel('Context layer',{exact:true}).selectOption('traffic');
 await expect(page.locator('.lens .content')).toContainText('matched sample sites');
 const siteValue=await page.getByLabel('Select traffic site',{exact:true}).locator('option').nth(1).getAttribute('value');
 await page.getByLabel('Select traffic site',{exact:true}).selectOption(siteValue);
 await page.getByLabel('Choose neighborhood',{exact:true}).selectOption('Como');
 await expect(page.getByLabel('Select traffic site',{exact:true})).toHaveValue('');
 await page.getByLabel('Choose neighborhood',{exact:true}).selectOption('Marcy Holmes');
 await page.getByLabel('Context layer',{exact:true}).selectOption('income');
 await expect(page.locator('.lens svg [role=button]')).toHaveCount(121);
 await page.locator('.lens').screenshot({path:'artifacts/fp2-income-lens.png'});
 const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze();
 expect(axe.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))).toEqual([]);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'artifacts/fp2-mobile.png',fullPage:true});
 expect(errors).toEqual([]);
});
test('FP2 exposes load failure rather than fabricated defaults',async({page})=>{
 await page.route('**/data/fp2-context.json',r=>r.fulfill({status:503,body:'unavailable'}));
 await page.goto('fp2/');await expect(page.getByRole('alert')).toContainText('Could not load');
 await expect(page.locator('.scatter circle')).toHaveCount(0);
});
